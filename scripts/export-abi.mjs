// Writes app/abi.js from the compiled MandateVault ABI.
//   npx hardhat compile && node scripts/export-abi.mjs
//   node scripts/export-abi.mjs path/to/MandateVault.json   (any JSON with an "abi" field)
import { readFileSync, writeFileSync } from "node:fs";

const src = process.argv[2] ?? "artifacts/contracts/MandateVault.sol/MandateVault.json";
const { abi } = JSON.parse(readFileSync(src, "utf8"));

const erc20Abi = [
  { type: "function", name: "balanceOf", stateMutability: "view", inputs: [{ name: "a", type: "address" }], outputs: [{ type: "uint256" }] },
  { type: "function", name: "allowance", stateMutability: "view", inputs: [{ name: "o", type: "address" }, { name: "s", type: "address" }], outputs: [{ type: "uint256" }] },
  { type: "function", name: "approve", stateMutability: "nonpayable", inputs: [{ name: "s", type: "address" }, { name: "v", type: "uint256" }], outputs: [{ type: "bool" }] },
  { type: "function", name: "symbol", stateMutability: "view", inputs: [], outputs: [{ type: "string" }] },
];

writeFileSync(
  "app/abi.js",
  "// Generated by scripts/export-abi.mjs from the compiled MandateVault. Do not edit by hand.\n" +
    `export const vaultAbi = ${JSON.stringify(abi)};\n` +
    `export const erc20Abi = ${JSON.stringify(erc20Abi)};\n`,
);
console.log(`app/abi.js: ${abi.length} entries`);
